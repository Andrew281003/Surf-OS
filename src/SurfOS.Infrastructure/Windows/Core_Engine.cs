    internal class Core_Engine
    {
        // =========================================================================
        // DEEP WINDOWS API HOOKS FOR WINDOW MANAGEMENT (user32.dll)
        // =========================================================================

        [DllImport("kernel32.dll", ExactSpelling = true)]
        private static extern IntPtr GetConsoleWindow();

        [DllImport("user32.dll", CharSet = CharSet.Auto, SetLastError = true)]
        private static extern bool ShowWindow(IntPtr hWnd, int nCmdShow);

        private const int SW_MAXIMIZE = 3;
        private const short HugeConsoleFontSize = 36;

        /// <summary>
        /// Forces the console window to maximize to full screen.
        /// </summary>
        public static void MaximizeWindow()
        {
            if (!OperatingSystem.IsWindows()) return;

            try
            {
                IntPtr consoleWindowHandle = GetConsoleWindow();
                if (consoleWindowHandle != IntPtr.Zero)
                {
                    ShowWindow(consoleWindowHandle, SW_MAXIMIZE);
                }
            }
            catch
            {
                // Failsafe in case the OS blocks the window resize
            }
        }


